/*
 * 中文时间表达守卫（v3.30）
 * ------------------------------------------------------------------
 * 三个 bug 是同一类病：用户这么写、代码不认，且**整条静默判失败**
 * （不是算错）——用户看到的是"选中了没反应"，比算错更难发现。
 *
 *   B 周X 前缀 + 时刻：`下周三下午2点` 认不出
 *     剥尾部周X 的正则没带上/下/本前缀，剩一个「下」→ leftover 非空 → null。
 *     WEEKDAY_RE（1156 行）本来就是带前缀的 —— 同一文件里的不一致。
 *
 *   C 时段别名：`周五上午10点` 认不出
 *     DAYPART_TAIL_RE 只用 key 拼，丢了 re 里的别名
 *     （上午/早晨/正午/晌午/黄昏/夜晚/半夜/午夜 全军覆没）。
 *     修法是 flatMap 拆 re 的字面写法，**不要加 alias**
 *     （单字「午/早/晚」有歧义，会误命中）。
 *
 *   D 阿拉伯日期：`2026-09-19下午3点` 认不出
 *     复合解析只认带「年月日」字样的日期，纯数字日期无处安放。
 *     兜底 `parseToDate` **必须放在 leftover 检查之前** ——
 *     放在之后的话 leftover 那句已经 `return null`，兜底永远到不了。
 *
 * 反证方法：
 *   B：把尾部周X 正则改回 /(?:周|星期|礼拜)\s*([一二三四五六日天1-7])$/
 *      → A 组第 1 条必须报红，而「周三下午2点」（无前缀）不受影响。
 *   C：DAYPART_TAIL_RE 改回 .map(t => t.key) → B 组「周五上午10点」报红，
 *      「周五早上10点」（key 里就有）不受影响。
 *   D：把 fallbackDate 那块删掉 → C 组全红。
 */

'use strict';

process.env.TZ = 'UTC';

const path = require('path');
const SRC = path.join(__dirname, '..', 'src');
const ta = require(path.join(SRC, 'timestamp.js'));

let pass = 0;
let fail = 0;
function check(name, cond, actual) {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (actual === undefined ? '' : ' → ' + actual)); }
}

/* 固定基准：2026-09-29（周二），否则「下周三」随运行日期漂移 */
const BASE = new Date(Date.UTC(2026, 8, 29));
/** 解析复合表达，返回 'YYYY-MM-DD HH:mm' 或 'null' */
function pc(text) {
  const d = ta.parseComposite(text, BASE, null);
  if (!d) return 'null';
  const p = (n) => String(n).padStart(2, '0');
  return d.getUTCFullYear() + '-' + p(d.getUTCMonth() + 1) + '-' + p(d.getUTCDate())
    + ' ' + p(d.getUTCHours()) + ':' + p(d.getUTCMinutes());
}

console.log('\n[A] 周X 前缀 + 时刻（B 项）');
/* 2026-09-29 是周二：下周三 = 10-07，本周五 = 10-02，下下周一 = 10-12 */
check('下周三下午2点 能解析', pc('下周三下午2点') !== 'null', pc('下周三下午2点'));
check('下周三下午2点 → 2026-10-07 14:00', pc('下周三下午2点') === '2026-10-07 14:00', pc('下周三下午2点'));
check('下周三（无时刻）能解析', pc('下周三') !== 'null', pc('下周三'));
check('周三下午2点（无前缀，回归）→ 2026-09-30 14:00', pc('周三下午2点') === '2026-09-30 14:00', pc('周三下午2点'));
check('下下周一下午3点 能解析', pc('下下周一下午3点') === '2026-10-12 15:00', pc('下下周一下午3点'));
check('本周五下午2点 能解析', pc('本周五下午2点') === '2026-10-02 14:00', pc('本周五下午2点'));

console.log('\n[B] 时段别名（C 项）');
/* 「上午」是「早上」的别名，不在 key 里；黄昏=22 点且带 pm 翻转 */
check('周五上午10点 能解析', pc('周五上午10点') !== 'null', pc('周五上午10点'));
check('周五上午10点 → 2026-10-02 10:00', pc('周五上午10点') === '2026-10-02 10:00', pc('周五上午10点'));
check('周五早上10点（key 里就有，回归）', pc('周五早上10点') === '2026-10-02 10:00', pc('周五早上10点'));
check('周五黄昏10点 → 22:00（别名 + pm 翻转）', pc('周五黄昏10点') === '2026-10-02 22:00', pc('周五黄昏10点'));
check('周五正午 能解析', pc('周五正午') === '2026-10-02 12:00', pc('周五正午'));
check('周五下午3点（回归）', pc('周五下午3点') === '2026-10-02 15:00', pc('周五下午3点'));

console.log('\n[C] 阿拉伯日期兜底（D 项）');
check('2026-09-19下午3点 → 2026-09-19 15:00', pc('2026-09-19下午3点') === '2026-09-19 15:00', pc('2026-09-19下午3点'));
check('2026-09-19 下午3点（带空格）', pc('2026-09-19 下午3点') === '2026-09-19 15:00', pc('2026-09-19 下午3点'));
check('2026/9/19下午3点', pc('2026/9/19下午3点') === '2026-09-19 15:00', pc('2026/9/19下午3点'));
check('2026年9月19日下午3点（中文，回归）', pc('2026年9月19日下午3点') === '2026-09-19 15:00', pc('2026年9月19日下午3点'));
check('明年12月的第49周周三下午2点（复合，回归）', pc('明年12月的第49周周三下午2点') === '2027-12-08 14:00', pc('明年12月的第49周周三下午2点'));
check('2026-09-19 12:45（带英文冒号时刻，回归）', pc('2026-09-19 12:45') === '2026-09-19 12:45', pc('2026-09-19 12:45'));

console.log('\n[D] 兜底不得误收垃圾');
/*
 * D 项风险最高（新增兜底分支，可能掩盖其他未识别片段）。
 * parseToDate 首尾锚定、不会把碎片当日期，所以这里必须确认它真的不误收。
 */
check('随便一段话下午3点 → null', pc('随便一段话下午3点') === 'null', pc('随便一段话下午3点'));
check('空串 → null', pc('') === 'null', pc(''));
check('纯数字 12345 → null（不当日期）', pc('12345') === 'null', pc('12345'));

console.log('\n' + (fail === 0 ? '全部通过 ✅' : fail + ' 项失败 ❌'));
console.log('套件: cnparse');
process.exit(fail === 0 ? 0 : 1);
